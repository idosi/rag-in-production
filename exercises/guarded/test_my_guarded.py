"""Tests for exercise 3c-3: wire cache + spend limit + cost around the pipeline.

Run:   uv run pytest exercises/guarded -q
Do not edit this file; edit my_guarded.py. Each test adds one idea.
"""

import pytest

from exercises.cache.my_cache import AnswerCache
from exercises.guarded.my_guarded import BudgetExceeded, GuardedPipeline
from exercises.spend.my_spend import SpendTracker
from rag.generator import NOT_FOUND
from rag.models import Answer, Chunk, RetrievedChunk


def _source():
    return RetrievedChunk(Chunk("doc", 0, "Heading", "http://u", "text"), 0.9)


class FakePipeline:
    """Pretends to be RAGPipeline. Counts calls; answers with fixed usage."""

    def __init__(self, text="the answer", with_sources=True, usage=None):
        self.calls = 0
        self.text = text
        self.with_sources = with_sources
        self.usage = usage if usage is not None else {"model": "m", "input_tokens": 1000, "output_tokens": 100}

    def ask(self, question):
        self.calls += 1
        sources = [_source()] if self.with_sources else []
        return Answer(text=self.text, sources=sources, cited=[1], usage=dict(self.usage))


def flat_cost(usage):
    """Every answer costs exactly 10 cents, whatever the usage says."""
    return 0.10


def make(inner, budget=1.00, **kw):
    return GuardedPipeline(
        inner=inner,
        cache=AnswerCache(max_items=10, ttl=60),
        spend=SpendTracker(daily_budget=budget),
        version="v1",
        cost_fn=kw.get("cost_fn", flat_cost),
    )


def test_1_a_miss_calls_the_pipeline_and_reports_its_cost():
    g = make(FakePipeline())
    a = g.ask("How do I X?")
    assert a.text == "the answer"
    assert a.usage["cost_usd"] == pytest.approx(0.10)
    assert a.usage["cache_hit"] is False
    assert g.spend.spent_today() == pytest.approx(0.10)


def test_2_the_same_question_again_is_served_from_cache_for_free():
    inner = FakePipeline()
    g = make(inner)
    g.ask("How do I X?")
    second = g.ask("  how do i x ")  # written differently, same key
    assert inner.calls == 1
    assert second.text == "the answer"
    assert second.usage["cache_hit"] is True
    assert second.usage["cost_usd"] == 0.0
    assert g.spend.spent_today() == pytest.approx(0.10)  # the hit cost nothing


def test_3_a_hit_does_not_change_the_answer_that_is_stored():
    # The first caller must still see cache_hit False afterwards; the stored
    # answer must not be mutated by the second call.
    inner = FakePipeline()
    g = make(inner)
    first = g.ask("How do I X?")
    g.ask("How do I X?")
    assert first.usage["cache_hit"] is False


def test_4_not_found_answers_are_not_cached():
    inner = FakePipeline(text=NOT_FOUND, with_sources=False)
    g = make(inner)
    g.ask("something odd")
    g.ask("something odd")
    assert inner.calls == 2


def test_5_over_budget_raises_before_calling_the_pipeline():
    inner = FakePipeline()
    g = make(inner, budget=0.10)
    g.ask("question one")  # costs 0.10: budget is now used up
    with pytest.raises(BudgetExceeded):
        g.ask("question two")
    assert inner.calls == 1


def test_6_cached_answers_are_still_served_when_the_budget_is_used_up():
    inner = FakePipeline()
    g = make(inner, budget=0.10)
    g.ask("question one")
    again = g.ask("question one")  # free, so it must not be blocked
    assert again.usage["cache_hit"] is True
    assert inner.calls == 1


def test_7_the_real_prices_are_used_by_default_cost_function():
    from exercises.guarded.my_guarded import cost_of

    # claude-haiku-5-5: $0.10 per 1M input, $0.50 per 1M output tokens.
    usage = {"model": "claude-haiku-5-5", "input_tokens": 1_000_000, "output_tokens": 1_000_000}
    assert cost_of(usage) == pytest.approx(0.60)
    assert cost_of({"model": "unknown-model", "input_tokens": 5, "output_tokens": 5}) == 0.0
