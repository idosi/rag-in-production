"""EXERCISE 3d-0: make the image listen on the port Cloud Run gives it.

Run:   uv run pytest exercises/deploy -q
This one is not Python: you edit the Dockerfile (the last line, CMD). Do not edit this file.

WHY
    Cloud Run does not ask which port your app uses. It TELLS the container, through the
    environment variable PORT (8080 today), and sends traffic only there. Our CMD has
    `--port 8000` hard-coded, so on Cloud Run the deploy fails with
    "The user-provided container failed to start and listen on the port defined by the
    PORT=8080 environment variable". Locally (docker compose) PORT is not set, and 8000
    must keep working.

THE SPEC
    1. CMD starts uvicorn on ${PORT}, and on 8000 when PORT is not set.
    2. uvicorn becomes the main process (PID 1), not a child of a shell.
    3. The HEALTHCHECK checks the same port the server listens on.

HINTS (open one at a time, only when stuck)
    1. The exec form CMD ["uvicorn", "--port", "$PORT"] does NOT expand variables: no shell
       runs it, so uvicorn gets the literal text "$PORT". You need a shell: CMD ["sh", "-c", "..."]
    2. In a shell, ${PORT:-8000} means "PORT, or 8000 if it is empty or unset".
    3. `exec uvicorn ...` replaces the shell with uvicorn. Why it matters: Cloud Run stops a
       container with SIGTERM sent to PID 1. A shell as PID 1 does not forward it, so
       uvicorn never runs the lifespan shutdown (closing the DB connection) and is killed
       10 seconds later.
    4. The HEALTHCHECK runs python -c "...". Inside Python, read the port with
       os.environ.get('PORT', '8000').
"""

import json
import re
import urllib.request
from pathlib import Path

DOCKERFILE = Path(__file__).resolve().parents[2] / "Dockerfile"


def last_instruction(name: str) -> str:
    """The last instruction of that kind, with `\\` continuation lines joined."""
    text = DOCKERFILE.read_text().replace("\\\n", " ")
    lines = [line.strip() for line in text.splitlines() if line.strip().startswith(name + " ")]
    assert lines, f"no {name} instruction in the Dockerfile"
    return lines[-1]


def test_1_cmd_uses_the_port_variable_with_8000_as_default():
    cmd = last_instruction("CMD")
    assert "${PORT:-8000}" in cmd, cmd
    assert "--port 8000" not in cmd  # the hard-coded port is gone


def test_2_cmd_runs_through_a_shell_so_the_variable_is_expanded():
    cmd = last_instruction("CMD")
    assert re.search(r'\[\s*"(/bin/)?sh"\s*,\s*"-c"', cmd), cmd


def test_3_uvicorn_replaces_the_shell_and_gets_sigterm():
    cmd = last_instruction("CMD")
    assert re.search(r"\bexec\s+uvicorn\b", cmd), cmd


def test_4_still_listens_on_all_interfaces():
    assert "--host 0.0.0.0" in last_instruction("CMD")


def test_5_healthcheck_checks_the_same_port():
    check = last_instruction("HEALTHCHECK")
    assert "PORT" in check and "8000" in check, check


def run_healthcheck(monkeypatch, port):
    """Run the HEALTHCHECK's Python code for real (urlopen replaced by a recorder)."""
    check = last_instruction("HEALTHCHECK")
    argv = json.loads(re.search(r"\bCMD\s+(\[.*\])", check).group(1))
    assert argv[:2] == ["python", "-c"], argv
    if port is None:
        monkeypatch.delenv("PORT", raising=False)
    else:
        monkeypatch.setenv("PORT", port)
    urls = []
    monkeypatch.setattr(urllib.request, "urlopen", lambda url, timeout=None: urls.append(url))
    exec(argv[2], {})  # raises if the code is broken (e.g. a bad % format)
    return urls


def test_6_healthcheck_really_runs_and_uses_the_port(monkeypatch):
    assert run_healthcheck(monkeypatch, "8080") == ["http://127.0.0.1:8080/health"]
    assert run_healthcheck(monkeypatch, None) == ["http://127.0.0.1:8000/health"]
